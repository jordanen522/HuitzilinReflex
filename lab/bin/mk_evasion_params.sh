#!/usr/bin/env bash
# mk_evasion_params.sh — generate a COMPLETE lab evasion params file from the
# shipped one, with meas_std_xyz_m overridden.
#
# WHY THIS EXISTS
#   week6_oracle.launch.py:151 passes `evasion_params` as the FIRST element of
#   the evasion node's `parameters=[...]`, with only use_sim_time overlaid on
#   top. So `evasion_params:=` REPLACES the shipped file — it does not overlay
#   it. A lab variant therefore has to be complete, and a hand-written complete
#   copy stops tracking src/ the moment anyone changes a default. A silently
#   stale copy is how an A/B ends up comparing two different baselines and
#   calling the difference an effect.
#
#   Deriving both arms from src/ means the only difference between them is the
#   one key this script writes, which is the entire point of an A/B.
#
# USAGE
#   mk_evasion_params.sh <out.yaml> <fwd> <left> <up>
#
#     mk_evasion_params.sh ~/hz_lab/params/evasion_mono.yaml 0.85 0.02 0.02
#     mk_evasion_params.sh ~/hz_lab/params/evasion_iso.yaml  0 0 0
#
#   (fwd, left, up) is a sigma triple in base_link FLU, matching the convention
#   in oracle_detector.yaml's noise_std_xyz_m. The all-zero form is the
#   DISABLED sentinel that evasion_node._resolve_meas_std_xyz reads as "use the
#   isotropic meas_std_m instead".
#
#   GENERATE THE CONTROL ARM THROUGH THIS SCRIPT TOO, with 0 0 0, rather than
#   pointing the control at the shipped file. Both arms then travel an
#   identical code path, so a bug in the generator shows up as a null instead
#   of as a fake effect.
#
# WHAT IS LOST
#   yaml.safe_load/safe_dump does not preserve comments, so the generated file
#   carries none of the shipped file's reasoning. That is acceptable for a lab
#   artefact and is exactly why the generated header points back at src/.

source "$HOME/hz_tools/hz_env.sh"          # before `set -u` (CLAUDE.md)
set -u

OUT="${1:?usage: mk_evasion_params.sh <out.yaml> <fwd> <left> <up>}"
FWD="${2:?usage: mk_evasion_params.sh <out.yaml> <fwd> <left> <up>}"
LEFT="${3:?usage: mk_evasion_params.sh <out.yaml> <fwd> <left> <up>}"
UP="${4:?usage: mk_evasion_params.sh <out.yaml> <fwd> <left> <up>}"

SRC="${SRC:-$HOME/huitzilin_ws/src/huitzilin_perception/params/evasion.yaml}"
[ -r "$SRC" ] || { echo "!! no shipped evasion.yaml at $SRC" >&2; exit 2; }

mkdir -p "$(dirname "$OUT")"

python3 - "$SRC" "$OUT" "$FWD" "$LEFT" "$UP" <<'PY'
import datetime
import sys

import yaml

src, out, fwd, left, up = sys.argv[1:6]

with open(src) as fh:
    doc = yaml.safe_load(fh)

# The node key is READ, never assumed. In ROS 2 a params file whose top-level
# key does not match the node name loads SILENTLY AS NOTHING -- no error, no
# warning, and the node runs on its declared defaults. test_hw_config.py exists
# because of that exact failure mode, and a generator that hardcoded "evasion"
# would reintroduce it the day the node is renamed.
keys = [k for k in doc if k != "/**"]
if len(keys) != 1:
    sys.exit("expected exactly one node key in %s, got %r" % (src, list(doc)))
node = keys[0]
params = doc[node]["ros__parameters"]

# Refuse to invent the key. A params file that declares a parameter the node
# does not declare is rejected at startup, so writing it blind would turn a
# stale-source problem into a bring-up failure 25 minutes later.
if "meas_std_xyz_m" not in params:
    sys.exit(
        "%s has no meas_std_xyz_m -- the shipped file is older than the "
        "feature. Rebuild/pull before generating." % src
    )

params["meas_std_xyz_m"] = [float(fwd), float(left), float(up)]

# use_sim_time is a launch argument only, never a params-file key
# (huitzilin_sim/clock_guard.py, and test_hw_config.py fails if it reappears).
# The shipped file does not carry it; assert rather than trust.
if "use_sim_time" in params:
    sys.exit("%s carries use_sim_time -- that key must stay a launch argument" % src)

stamp = datetime.datetime.now().astimezone().isoformat(timespec="seconds")
header = (
    "# GENERATED by lab/bin/mk_evasion_params.sh -- do not edit by hand.\n"
    "# source:    %s\n"
    "# generated: %s\n"
    "# node key:  %s   (read from the source, never assumed)\n"
    "# override:  meas_std_xyz_m: [%s, %s, %s]"
    "   (all-zero = disabled -> isotropic meas_std_m)\n"
    "#\n"
    "# COMPLETE on purpose: `evasion_params:=` replaces the shipped file rather\n"
    "# than overlaying it. Regenerate instead of editing -- an edited copy stops\n"
    "# tracking src/ and turns the next A/B into a comparison of two different\n"
    "# baselines. Comments from the source are not preserved; read src/ for the\n"
    "# reasoning behind any value here.\n"
) % (src, stamp, node, fwd, left, up)

with open(out, "w") as fh:
    fh.write(header)
    yaml.safe_dump(
        {node: {"ros__parameters": params}},
        fh,
        default_flow_style=False,
        sort_keys=False,
    )

print(
    "wrote %s\n  node=%s  meas_std_xyz_m=%s  (%d keys carried over)"
    % (out, node, params["meas_std_xyz_m"], len(params))
)
PY
rc=$?
[ "$rc" -eq 0 ] || exit "$rc"

# Read the generated file back. The generator asserting its own output proves
# nothing about what landed on disk; this is the line that would catch a
# truncated write or a surprising yaml dialect.
echo "[readback] $(grep -n 'meas_std_xyz_m' "$OUT")"
